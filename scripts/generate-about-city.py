def sign(x, y, label):
    width = len(label) * 6 + 12
    rect(x + 3, y + 21, 2, 8, "#73728b")
    rect(x + width - 5, y + 21, 2, 8, "#73728b")
    rect(x, y, width, 22, "#8b8eab")
    flush()
    rect(x + 2, y + 2, width - 4, 18, "#2a3045")
    flush()
    rect(x + 4, y + 4, width - 8, 1, "#6e718e")
    rect(x + 4, y + 17, width - 8, 1, "#6e718e")
    for i, char in enumerate(label):
        for yy, row in enumerate(font[char]):
            for xx, bit in enumerate(row):
                if bit == "1":
                    rect(x + 6 + i * 6 + xx, y + 7 + yy, 1, 1, "#d1bacf")
    beacon(x, y - 1)
    beacon(x + width - 1, y - 1)
    flush()


