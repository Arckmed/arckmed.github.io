"""Build the About footer's original pixel skyline. Run with Python 3 (no dependencies)."""

from pathlib import Path
from random import Random


rng = Random(317)
parts = []
pixels = {}


def rect(x, y, w, h, color):
    pixels.setdefault(color, []).append(f"M{x} {y}h{w}v{h}h{-w}z")


def flush():
    for color, paths in pixels.items():
        parts.append(f'<path fill="{color}" d="{"".join(paths)}"/>')
    pixels.clear()


def polygon(points, color):
    flush()
    parts.append(f'<polygon fill="{color}" points="{points}"/>')


def beacon(x, y):
    rect(x, y - 3, 1, 6, "#9e637c")
    rect(x - 2, y - 1, 5, 2, "#c78f8f")
    rect(x, y - 1, 1, 1, "#f1d1b0")
    flush()
    parts.append(f'<rect data-city-beacon="" x="{x}" y="{y-1}" width="1" height="1" fill="#f1d1b0"/>')


def building(x, base, w, h, depth, style, palette):
    """Front faces are level; every depth edge recedes right and up at 2:1."""
    face, side, roof, light = palette
    top = base - h
    dy = depth // 2
    front_top = top + dy
    polygon(f"{x},{front_top} {x+depth},{top} {x+w+depth},{top} {x+w+depth},{base-dy} {x+w},{base} {x},{base}", "#171d29")
    rect(x + 1, front_top + 1, w - 1, base - front_top - 1, face)
    flush()
    polygon(f"{x+w},{front_top} {x+w+depth},{top} {x+w+depth},{base-dy} {x+w},{base}", side)
    polygon(f"{x},{front_top} {x+depth},{top} {x+w+depth},{top} {x+w},{front_top}", roof)
    rect(x, front_top, w, 1, light)
    flush()

    # Each facade has its own construction, rather than one repeated window grid.
    animated_windows = []
    for y in range(top + dy + 7, base - 5, 6 if style != "bands" else 5):
        if style == "bands":
            rect(x + 3, y + 3, w - 5, 1, "#151d2a")
            for col in range(x + 4, x + w - 7, 7):
                color = rng.choice([light, light, "#8ca6b8", "#658799"])
                rect(col, y, 5, 1, color)
                rect(col, y + 1, rng.choice([2, 4, 5]), 1, color)
                if (col * 7 + y * 3) % 41 == 0:
                    animated_windows.append((col, y, 5, 1, color))
        else:
            for col in range(x + 4, x + w - 3, 6):
                color = rng.choices([light, "#dcc4ae", "#6b718c", "#293647"], [5, 1, 2, 3])[0]
                rect(col, y, 3 if style == "grid" else 2, 3, color)
                if (col * 7 + y * 3) % 41 == 0:
                    animated_windows.append((col, y, 3 if style == "grid" else 2, 3, color))
                if style == "grid":
                    rect(col - 1, y + 3, 4, 1, "#171f30")
        for col in range(3, depth - 1, 4):
            sy = y - col // 2
            if sy + 2 < base - col // 2 - 4:
                rect(x + w + col, sy, 2, 2, rng.choice(["#41516e", "#796b8a", light]))
    flush()

    # Keep interactive windows in their building's paint order for occlusion.
    for wx, wy, ww, wh, color in animated_windows:
        parts.append(f'<rect data-city-window="" x="{wx}" y="{wy}" width="{ww}" height="{wh}" fill="{color}"/>')

    if style == "columns":
        for col in range(x + 2, x + w, 12):
            rect(col, top + dy + 4, 1, h - dy - 4, roof)
    elif style == "grid":
        for y in range(top + dy + 11, base - 5, 18):
            rect(x + 1, y, w - 1, 1, roof)
    rect(x + 2, base - 5, w - 4, 5, "#1b2130")
    for col in range(x + 6, x + w - 4, 10):
        rect(col, base - 4, 4, 3, light)
    flush()

    # Roof equipment uses the same projection and sits on the roof plane.
    plant_x = x + depth // 2 + w // 3
    plant_y = front_top - dy // 2
    plant_w = max(6, w // 4)
    rect(plant_x, plant_y - 4, plant_w, 4, side)
    flush()
    polygon(f"{plant_x},{plant_y-4} {plant_x+4},{plant_y-6} {plant_x+plant_w+4},{plant_y-6} {plant_x+plant_w},{plant_y-4}", "#a092a7")
    polygon(f"{plant_x+plant_w},{plant_y-4} {plant_x+plant_w+4},{plant_y-6} {plant_x+plant_w+4},{plant_y-2} {plant_x+plant_w},{plant_y}", "#343447")
    for col in range(plant_x + 2, plant_x + plant_w - 1, 3):
        rect(col, plant_y - 3, 1, 2, "#697286")
    beacon(x + 2, front_top - 1)
    beacon(x + w + depth - 2, top - 1)
    flush()


parts.append('<svg xmlns="http://www.w3.org/2000/svg" width="960" height="320" viewBox="0 0 960 320" shape-rendering="crispEdges">')
